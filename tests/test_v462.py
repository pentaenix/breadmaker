from source_contracts import frontend_source_from_app_path
from pathlib import Path


def test_v462_metro_layout_is_component_planned_and_distance_preserving():
    js=frontend_source_from_app_path(Path('static/app.js'))
    assert 'function metroConnectedComponents' in js
    assert 'function metroComponentTerritories' in js
    assert 'function metroPlanLineRoute' in js
    assert 'function metroResolveLineFractions' in js
    assert 'function metroRouteSelfIntersects' in js
    assert 'turnBudget=metroLineTurnBudget(line)' in js
    assert 'function metroTerrainFamily' in js
    assert "footer.textContent='Breadmaker'" in js
    assert "'data-terrain-family':plan.family" in js
    assert "'stroke-dasharray':'1.15 1.15'" in js
    assert tuple(map(int,Path('VERSION').read_text(encoding='utf-8').strip().split('.'))) >= (4,6,0)


def test_v462_legend_is_conditional_and_span_uses_walk_section_not_square():
    js=frontend_source_from_app_path(Path('static/app.js'))
    assert "if(model.legend.hasStation)addSymbol('Station','station')" in js
    assert "if(model.legend.hasInterchange)addSymbol('Interchange','transfer')" in js
    assert "if(model.legend.hasSpan)addSymbol('Span / phase','span')" in js
    assert 'metroRenderSpan(spanGroup,span)' in js
    assert "class:'metro-span-tick'" in js
    assert 'metroSolidRoutePath(entry)' in js
    assert 'Generated by Breadmaker' not in js
