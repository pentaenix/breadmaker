from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, ContextManager, Protocol

from auth.identity import Actor
from auth.sessions import SessionService
from auth.accounts import AccountIdentityService


@dataclass(frozen=True)
class ProjectRequestContext:
    """Environment-neutral identity for one request/task project binding."""
    project_id: str
    actor: Actor


@dataclass(frozen=True)
class StoredAsset:
    """Logical project asset write result with no filesystem requirement."""
    api_path: str
    name: str
    digest: str
    created: bool
    object_name: str | None = None
    object_generation: int | None = None


class ProjectContextProvider(Protocol):
    def current(self) -> ProjectRequestContext | None: ...
    def bind(self, project_id: str | None = None, *, user_id: str | None = None, require_membership: bool = True) -> ContextManager[ProjectRequestContext]: ...


class IdentityProvider(Protocol):
    def request_user_id(self, explicit_user_id: str | None = None) -> str: ...
    def active_profile_id(self) -> str: ...
    def current_profile(self, user_id: str | None = None) -> dict[str, Any]: ...
    def profiles(self) -> list[dict[str, Any]]: ...
    def create_profile(self, display_name: str) -> dict[str, Any]: ...
    def activate_profile(self, user_id: str) -> None: ...
    def update_profile(self, display_name: str, user_id: str | None = None) -> dict[str, Any]: ...
    def avatar_bytes(self, user_id: str) -> bytes | None: ...
    def save_avatar(self, payload: bytes, user_id: str | None = None) -> dict[str, Any]: ...
    def remove_avatar(self, user_id: str | None = None) -> dict[str, Any]: ...
    def current_actor(self, project_id: str | None = None, *, require_membership: bool = True, user_id: str | None = None) -> Actor: ...


class AuthorizationService(Protocol):
    def can(self, permission: str, project_id: str | None = None) -> bool: ...
    def require(self, permission: str, project_id: str | None = None) -> Actor: ...


class ProjectRepository(Protocol):
    """Environment-neutral project catalog/membership operations.

    Filesystem package/recovery helpers intentionally live in NativeProjectStore.
    Cloud adapters must not be forced to manufacture local filesystem objects merely
    to satisfy the project catalog contract.
    """
    def init(self) -> None: ...
    def list(self, user_id: str | None = None) -> list[dict[str, Any]]: ...
    def active_id(self) -> str | None: ...
    def active(self) -> dict[str, Any] | None: ...
    def get(self, project_id: str) -> dict[str, Any]: ...
    def create(self, name: str, *, activate: bool = True, owner_user_id: str | None = None) -> dict[str, Any]: ...
    def activate(self, project_id: str, *, user_id: str | None = None) -> dict[str, Any]: ...
    def rename(self, project_id: str, name: str) -> dict[str, Any]: ...
    def delete(self, project_id: str, *, permanent: bool = False) -> Any: ...
    def members(self, project_id: str) -> list[dict[str, Any]]: ...
    def membership(self, project_id: str, user_id: str) -> dict[str, Any] | None: ...
    def add_member(self, project_id: str, user_id: str, role: str) -> dict[str, Any]: ...
    def remove_member(self, project_id: str, user_id: str) -> Any: ...
    def profile_project_target(self, user_id: str) -> str | None: ...
    def recovery_candidates(self) -> list[dict[str, Any]]: ...
    def list_trash(self, user_id: str | None = None) -> list[dict[str, Any]]: ...
    def restore_from_trash(self, trash_id: str, *, user_id: str | None = None) -> dict[str, Any]: ...


class NativeProjectStore(Protocol):
    """Explicit local/native filesystem bridge.

    This is not a contract a Cloud Run adapter must implement.  Every use of this
    port is intentional migration debt and is inventoried for Milestone 5.
    """
    @property
    def root(self) -> Path: ...
    def import_package(self, path: Path, *, name_override: str | None = None, owner_user_id: str | None = None) -> dict[str, Any]: ...
    def export_package(self, project_id: str, out: Path) -> Any: ...
    def export_all_data(self, out: Path) -> Any: ...
    def verify_package(self, path: Path) -> dict[str, Any]: ...
    def inspect_package_metadata(self, path: Path) -> dict[str, Any]: ...
    def read_manifest(self, root: Path) -> dict[str, Any]: ...


class AssetStore(Protocol):
    """Environment-neutral content-addressed project asset port."""
    def exists(self, name_or_api_path: str) -> bool: ...
    def read_blob(self, name_or_api_path: str) -> bytes: ...
    def put_blob(self, blob: bytes, ext: str) -> StoredAsset: ...
    def discard_uncommitted(self, asset: StoredAsset) -> None: ...


class NativeAssetStore(Protocol):
    """Local-only materialization helpers retained for legacy exporters/health."""
    @property
    def root(self) -> Path: ...
    def resolve_name(self, name: str, *, require_exists: bool = True) -> Path: ...
    def resolve_api_path(self, api_path: str, *, require_exists: bool = True) -> Path: ...
    def stage_upload(self, ext: str) -> Path: ...
    def finalize_staged(self, staged: Path, ext: str) -> tuple[str, Path, bool, str]: ...


class HistoryStore(Protocol):
    def list_revisions(self) -> list[dict[str, Any]]: ...
    def sync_remote(self, project_id: str, revision_id: str | None = None) -> Any: ...
    def retention_settings(self) -> dict[str, Any]: ...
    def update_retention(self, value: str) -> dict[str, Any]: ...
    def run_maintenance(self, project_id: str) -> Any: ...
    def repair_local_from_destination(self, destination_id: str, *, project_id: str, revision_id: str | None = None) -> Any: ...
    def remote_privacy_barrier(self) -> ContextManager[Any]: ...


class NativeHistoryStore(Protocol):
    def revision_store_for(self, project_root: Path): ...


class BackupStore(Protocol):
    def privacy_barrier(self) -> ContextManager[Any]: ...
    def erase_known_managed_data(self) -> dict[str, Any]: ...
    def catch_up(self, project_id: str | None = None, **kwargs) -> dict[str, Any]: ...
    def destinations(self) -> list[dict[str, Any]]: ...
    def add_destination(self, path_value: str, *, destination_kind: str = 'folder') -> dict[str, Any]: ...
    def update_destination(self, destination_id: str, **kwargs) -> dict[str, Any]: ...
    def remove_destination(self, destination_id: str) -> Any: ...
    def destination_backups(self, destination_id: str) -> Any: ...
    def discover_destination_backups(self, destination_id: str) -> Any: ...
    def google_oauth_config(self) -> dict[str, Any]: ...
    def begin_google_oauth(self, redirect_uri: str, **kwargs) -> dict[str, Any]: ...
    def complete_google_oauth(self, state: str, code: str) -> dict[str, Any]: ...
    def fail_google_oauth(self, state: str, error: str) -> Any: ...
    def google_oauth_status(self, state: str) -> dict[str, Any]: ...
    def add_webdav_destination(self, endpoint: str, username: str, password: str, name: str) -> dict[str, Any]: ...
    def reconnect_webdav_destination(self, destination_id: str, endpoint: str, username: str, password: str, name: str) -> dict[str, Any]: ...


class NativeBackupStore(Protocol):
    @property
    def recovery_dir(self) -> Path: ...
    def materialize_destination_backup(self, destination_id: str, filename: str) -> ContextManager[Path]: ...


class ProjectUsageService(Protocol):
    """Quota/usage projection without exposing project filesystem handles."""
    def owner_project_count(self, owner_user_id: str) -> int: ...
    def owner_storage_bytes(self, owner_user_id: str, *, stop_after: int | None = None) -> int: ...
    def project_storage_bytes(self, project_id: str, *, stop_after: int | None = None) -> int: ...


class CapabilityProvider(Protocol):
    @property
    def mode(self) -> str: ...
    def public(self) -> dict[str, bool]: ...
    def metadata(self) -> dict[str, Any]: ...
    def supports(self, capability: str) -> bool: ...


@dataclass(frozen=True)
class RuntimeServices:
    mode: str
    context: ProjectContextProvider
    identity: IdentityProvider
    authorization: AuthorizationService
    projects: ProjectRepository
    assets: AssetStore
    history: HistoryStore
    backups: BackupStore
    usage: ProjectUsageService
    capabilities: CapabilityProvider
    sessions: SessionService
    accounts: AccountIdentityService
    # Explicit native/local bridges.  Serverless hosted composition is expected to
    # leave these as None once Milestone 5 removes the inventoried legacy callers.
    native_projects: NativeProjectStore | None = None
    native_assets: NativeAssetStore | None = None
    native_history: NativeHistoryStore | None = None
    native_backups: NativeBackupStore | None = None
    # Complete hosted-only derivative bundle; absent unless explicitly activated.
    narration: Any | None = None
