from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "docs" / "HOSTED_DATA_MODEL_V1.json"
OUT = ROOT / "src" / "hosted" / "firestore" / "model_registry.py"


def _rows() -> list[dict[str, str]]:
    model = json.loads(MODEL.read_text(encoding="utf-8"))
    out: dict[str, dict[str, str]] = {}
    claimed_paths: set[str] = set()
    for row in model["schema42_mappings"]:
        if row["hosted_store"] not in {"firestore", "hybrid"}:
            continue
        path = row.get("firestore_path")
        if not path or "+" in path or ".status=" in path or path in claimed_paths:
            continue
        claimed_paths.add(path)
        out[row["logical_entity"]] = {
            "logical_entity": row["logical_entity"],
            "path_template": path,
            "authorization_policy": row["authorization_policy"],
            "concurrency_policy": row["concurrency_policy"],
            "hosted_store": row["hosted_store"],
        }
    for row in model["non_sql_state_mappings"]:
        if row["hosted_store"] not in {"firestore", "hybrid"}:
            continue
        path = row.get("firestore_path") or row.get("path")
        if not path or "+" in path or ".status=" in path or path in claimed_paths:
            continue
        claimed_paths.add(path)
        out.setdefault(row["logical_entity"], {
            "logical_entity": row["logical_entity"],
            "path_template": path,
            "authorization_policy": row["authorization_policy"],
            "concurrency_policy": row["concurrency_policy"],
            "hosted_store": row["hosted_store"],
        })
    return [out[key] for key in sorted(out)]


def render() -> str:
    lines = [
        "from __future__ import annotations",
        "",
        "# Generated by scripts/generate_hosted_firestore_registry.py from the frozen",
        "# hosted data-model contract. Do not hand-edit collection/path policy here.",
        "from .contracts import ModelContract",
        "",
        "MODELS: dict[str, ModelContract] = {",
    ]
    for row in _rows():
        lines += [
            f"    {row['logical_entity']!r}: ModelContract(",
            f"        logical_entity={row['logical_entity']!r},",
            f"        path_template={row['path_template']!r},",
            f"        authorization_policy={row['authorization_policy']!r},",
            f"        concurrency_policy={row['concurrency_policy']!r},",
            f"        hosted_store={row['hosted_store']!r},",
            "    ),",
        ]
    lines += ["}", "", "def model_for(logical_entity: str) -> ModelContract:", "    try:", "        return MODELS[str(logical_entity)]", "    except KeyError as exc:", "        raise KeyError(f'HOSTED_MODEL_UNKNOWN:{logical_entity}') from exc", ""]
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
