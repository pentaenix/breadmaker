#!/usr/bin/env python3
"""Review-pinned release firewall (source only, no tests or network).

The JSON digest inventory is deliberately NOT regenerated by VERSION bumps.
If this check fails, review the protected source diff before intentionally
updating its manifest entry. No auto-accept or hash-repair mode exists here.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "scripts/protected_release_sha256.json"
PROTECTED_PATHS = frozenset({
    "scripts/verify_release.py",
    "tests/conftest.py",
    "src/runtime/local.py",
    "src/hosted/firestore/repositories.py",
    "src/hosted/storage/publication.py",
    "requirements.txt",
})


def _unique_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    output: dict[str, object] = {}
    for key, value in pairs:
        if key in output:
            raise ValueError(f"Duplicate protected manifest key: {key}")
        output[key] = value
    return output


def validate(root: Path = ROOT) -> tuple[str, ...]:
    """Raise if any audited source byte differs from the explicit pinned digest.

    Do not auto-refresh digests: a real code change requires a human diff review.
    The set of protected paths is hard-coded separately to prevent the manifest
    from silently removing a protected file.
    """
    source = root / MANIFEST
    data = json.loads(source.read_text(encoding="utf-8"), object_pairs_hook=_unique_object)
    if not isinstance(data, dict) or set(data) != {"schema", "protected_files"} or data["schema"] != 1:
        raise ValueError("Unsupported protected-file manifest structure")
    expected = data["protected_files"]
    if not isinstance(expected, dict) or set(expected) != PROTECTED_PATHS:
        missing = sorted(PROTECTED_PATHS - set(expected)) if isinstance(expected, dict) else sorted(PROTECTED_PATHS)
        extra = sorted(set(expected) - PROTECTED_PATHS) if isinstance(expected, dict) else []
        raise ValueError(f"Protected-file manifest coverage changed: missing={missing}, unexpected={extra}")

    mismatches = []
    for relative in sorted(PROTECTED_PATHS):
        pinned = expected[relative]
        if not isinstance(pinned, str) or not re.fullmatch(r"[0-9a-f]{64}", pinned):
            raise ValueError(f"Invalid pinned SHA-256 for {relative}")
        path = root / relative
        if not path.is_file() or path.is_symlink():
            mismatches.append(f"{relative}: missing file or symlink")
            continue
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != pinned:
            mismatches.append(f"{relative}: pinned {pinned}, actual {actual}")
    if mismatches:
        raise ValueError(
            "PROTECTED_FILE_INTEGRITY_MISMATCH; audit the source diff before "
            "updating the pinned manifest: " + "; ".join(mismatches)
        )
    return tuple(sorted(PROTECTED_PATHS))


def main() -> None:
    try:
        files = validate()
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Protected-file integrity FAILED: {exc}") from exc
    print(f"Protected-file integrity PASS: {len(files)} reviewed source files")


if __name__ == "__main__":
    main()
