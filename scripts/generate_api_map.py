#!/usr/bin/env python3
from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
API=ROOT/'src'/'api'
VERSION=(ROOT/'VERSION').read_text(encoding='utf-8').strip()
PLATFORM_ORDER=('project_management',)
PLATFORM_PACKAGE_ROUTE_ORDER={
    'project_management':('profiles','workspace','metadata','destructive_actions','projects','members','packages','json_transfer','assets','health'),
}
MODULE_ORDER=(
    'manuscript','annotations','comments','reviews','tasks','canvas','icon_markers',
    'maps','workspace_tools','find_replace','checkpoints','durability','import_export',
)
PACKAGE_ROUTE_ORDER={
    'manuscript':('document','images','chapter_structure','chapters','scenes','narration','narration_voices','narration_pronunciation'),
    'reviews':('presets','portable','reader','questionnaires','feedback','participants','markers','lifecycle'),
    'canvas':('populate','registry','versions','lifecycle','nodes','edges','structure'),
    'tasks':('lifecycle','milestones','duplication'),
    'maps':('lifecycle','lines','items','junctions','layout','populate'),
    'durability':('cuts','history','undo','history_baseline','recovery','backup_destinations','recovery_backups','backup_inventory','backups'),
    'checkpoints':('lifecycle','comparison','apply'),
    'import_export':('docx_import','docx_export','pdf_export','assets'),
    'workspace_tools':('references','bookmark','ui_state','documents'),
    'annotations':('routes',),
    'comments':('routes',),
    'find_replace':('routes',),
    'icon_markers':('routes',),
}


def routes_for(path:Path) -> list[dict]:
    tree=ast.parse(path.read_text(encoding='utf-8'))
    routes=[]
    for node in tree.body:
        if not isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef)):continue
        for dec in node.decorator_list:
            if not (isinstance(dec,ast.Call) and isinstance(dec.func,ast.Attribute) and isinstance(dec.func.value,ast.Name) and dec.func.value.id=='router' and dec.func.attr in {'get','post','put','patch','delete'}):continue
            route={'method':dec.func.attr.upper(),'path':'?','function':node.name,'line':node.lineno,'file':path.relative_to(ROOT).as_posix()}
            if dec.args and isinstance(dec.args[0],ast.Constant):route['path']=str(dec.args[0].value)
            routes.append(route)
    return routes


def domain_files(name:str) -> list[Path]:
    file=API/f'{name}.py'
    if file.is_file():return [file]
    package=API/name
    order=PACKAGE_ROUTE_ORDER.get(name) or PLATFORM_PACKAGE_ROUTE_ORDER.get(name)
    if package.is_dir() and order:
        return [package/f'{part}.py' for part in order]
    if package.is_dir():
        return [p for p in sorted(package.glob('*.py')) if p.name!='__init__.py']
    raise FileNotFoundError(name)


def main() -> None:
    domains=[]
    lines=[
        '# Breadmaker API Code Map','',
        'Generated by `scripts/generate_api_map.py`. Do not hand-edit route entries.','',
        '**Rule:** locate the domain here first, then edit the named owner. `src/app.py` is composition-only; shared platform concerns live under cohesive `src/backend/*` owners.','',
    ]
    platform_domains=[]
    lines.extend(['## Platform HTTP domains',''])
    for name in PLATFORM_ORDER:
        files=domain_files(name);routes=[]
        for path in files:routes.extend(routes_for(path))
        owner=API/name/'__init__.py'
        platform_domains.append({'module':f'api.{name}','file':owner.relative_to(ROOT).as_posix(),'routes':routes})
        lines.extend([f'### `{name}` — `{owner.relative_to(ROOT).as_posix()}`','',f'{len(routes)} HTTP routes.',''])
        current=None
        for route in routes:
            if route['file']!=current:
                current=route['file'];lines.append(f'#### `{current}`')
            lines.append(f"- `{route['method']:6s} {route['path']}` → `{route['function']}()` (line {route['line']})")
        lines.append('')
    lines.extend(['## Feature domains',''])
    for name in MODULE_ORDER:
        files=domain_files(name)
        routes=[]
        for path in files:routes.extend(routes_for(path))
        owner=(API/f'{name}.py') if (API/f'{name}.py').is_file() else API/name/'__init__.py'
        domains.append({'module':f'api.{name}','file':owner.relative_to(ROOT).as_posix(),'routes':routes})
        lines.extend([f'## `{name}` — `{owner.relative_to(ROOT).as_posix()}`','',f'{len(routes)} HTTP routes.',''])
        current=None
        for route in routes:
            if route['file']!=current:
                current=route['file'];lines.append(f'### `{current}`')
            lines.append(f"- `{route['method']:6s} {route['path']}` → `{route['function']}()` (line {route['line']})")
        lines.append('')
    (API/'route_manifest.json').write_text(json.dumps({'schema':3,'generated_for':VERSION,'platform_domains':platform_domains,'domains':domains},indent=2)+'\n',encoding='utf-8')
    (API/'CODEMAP.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'wrote src/api/CODEMAP.md and route_manifest.json ({sum(len(d["routes"]) for d in platform_domains)} platform + {sum(len(d["routes"]) for d in domains)} feature route decorators)')

if __name__=='__main__':main()
